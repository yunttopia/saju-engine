// Generates src/korean-lunar-table.ts from lunar-javascript new moons and solar terms (run: npm run make:lunar-table).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import LunarPkg from 'lunar-javascript';
import { buildMonths, DAY, type Source } from './korean-lunar-core';

const SX = LunarPkg.ShouXingUtil;
const J2000 = 2451545;
const jdToMs = (jd: number) => (jd - 2440587.5) * DAY;

export const lunarJsSource: Source = {
  newMoonsUT(fromMs, toMs) {
    const out: number[] = [];
    for (let n = Math.floor((fromMs - jdToMs(J2000)) / DAY / 29.530588853) - 2; ; n++) {
      const t = SX.msaLonT(n * SX.PI_2) * 36525;
      const ms = jdToMs(J2000 + t - SX.dtT(t));
      if (ms < fromMs) continue;
      if (ms > toMs) break;
      out.push(ms);
    }
    return out;
  },
  principalTermsUT(fromMs, toMs) {
    const out: { ms: number; lon: number }[] = [];
    for (let k = Math.floor(((fromMs - jdToMs(J2000)) / DAY / 365.2422) * 12) - 2; ; k++) {
      const t = SX.saLonT((k * Math.PI) / 6) * 36525;
      const ms = jdToMs(J2000 + t - SX.dtT(t));
      if (ms < fromMs) continue;
      if (ms > toMs) break;
      out.push({ ms, lon: (((k % 12) + 12) % 12) * 30 });
    }
    return out;
  },
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {

  const first = Date.UTC(1900, 0, 1) / DAY;
  const last = Date.UTC(2099, 11, 31) / DAY;
  const months = buildMonths(lunarJsSource, 1899, 2100).filter((m) => m.endDay > first && m.startDay <= last);

  const byYear = new Map<number, typeof months>();
  for (const m of months) byYear.set(m.year, [...(byYear.get(m.year) ?? []), m]);
  const lines: string[] = [];
  for (const [year, ms] of byYear) {
    const d = new Date(ms[0].startDay * DAY).toISOString().slice(0, 10).replaceAll('-', '');
    const leap = ms.find((m) => m.leap)?.month ?? 0;
    const bits = ms.map((m) => (m.endDay - m.startDay === 30 ? '1' : m.endDay - m.startDay === 29 ? '0' : 'X')).join('');
    if (bits.includes('X')) throw new Error(`bad month length ${year}`);
    lines.push(`${year}|${d}|${ms[0].month}|${leap}|${bits}`);
  }
  const body = `// Generated by tools/make-korean-lunar-table.ts. Do not edit by hand.
// Korean lunar calendar: ${lines.length} years, ${months.length} months, covering solar 1900-01-01 to 2099-12-31.
// Format: year|solar start of first month|first month number|leap month (0 = none)|month length bits (1 = 30 days, 0 = 29, in order incl. leap)
export const KOREAN_LUNAR_TABLE: readonly string[] = [
${lines.map((l) => `  '${l}',`).join('\n')}
];
`;
  const target = fileURLToPath(new URL('../korean-lunar-table.ts', import.meta.url));
  writeFileSync(target, body);
  console.log(`${lines.length} years, ${months.length} months → ${target}`);
}
